/**
 * Экранирование пользовательских значений перед вставкой в текст сообщений
 * Telegram/MAX ботов, отправляемых с `parse_mode: 'HTML'` / `format: 'html'`.
 * Сообщения строятся из шаблонных строк, где статическую разметку (<b>, \n)
 * задаёт наш же код, а пользовательские значения (причина отмены, текст
 * поддержки, ФИО, марка/модель, username и т.п.) подставляются как есть —
 * без экранирования человек мог бы вставить свой `<b>`/`<a href=...>` и
 * исказить форматирование или содержание чужого сообщения. Экранировать
 * нужно только эти значения, а не всю строку целиком (иначе потерялась бы
 * собственная разметка).
 */
export function escapeBotHtml(value: string | number | null | undefined): string {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}
