/** Экранирование для вставки текста в HTML — тексты статичны и заданы нами, но привычка не помешает. */
function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export function userAgreementHtml(): string {
  const paragraphs = USER_AGREEMENT_TEXT.split('\n\n').map((block) => {
    const lines = block.split('\n').map(escapeHtml);
    const [heading, ...rest] = lines;
    const isHeading = /^\d\./.test(heading) && rest.length === 0;
    if (isHeading) return `<h3>${heading}</h3>`;
    return `<p>${lines.join('<br/>')}</p>`;
  });
  return paragraphs.join('\n');
}
